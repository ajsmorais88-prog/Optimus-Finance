-- BLOCO — Identidades, hashes de senha e perfis; não armazena as finanças.
CREATE TABLE IF NOT EXISTS public.app_users (
    id BIGSERIAL PRIMARY KEY,
    login VARCHAR(64) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('administrador', 'editor')),
    workspace_id BIGINT NOT NULL DEFAULT 1 REFERENCES public.workspaces (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


ALTER TABLE public.app_users
ADD COLUMN IF NOT EXISTS workspace_id BIGINT NOT NULL DEFAULT 1 REFERENCES public.workspaces (id);


-- BLOCO — Contadores compartilhados de tentativas de autenticação.
CREATE TABLE IF NOT EXISTS public.auth_rate_limits (
    bucket TEXT PRIMARY KEY,
    attempts INTEGER NOT NULL,
    window_started_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- A senha nova invalida sessões antigas; exclusão remove o acesso sem apagar finanças.
ALTER TABLE public.app_users
ADD COLUMN IF NOT EXISTS session_version INTEGER NOT NULL DEFAULT 0;


ALTER TABLE public.app_users
ADD COLUMN IF NOT EXISTS deleted_at TIMESTAMPTZ;


-- Push: assinaturas criptografadas e canais exclusivos do usuário autenticado.
CREATE TABLE IF NOT EXISTS public.push_subscriptions (
    endpoint_hash TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.app_users (id),
    session_version INTEGER NOT NULL,
    subscription BYTEA NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


CREATE TABLE IF NOT EXISTS public.pluggy_push_channels (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.app_users (id),
    client_hash TEXT NOT NULL,
    secret BYTEA NOT NULL,
    webhook_id TEXT,
    UNIQUE (user_id, client_hash)
);


CREATE TABLE IF NOT EXISTS public.push_events (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.app_users (id),
    route TEXT NOT NULL CHECK (
        route IN ('bank_account', 'card_bill', 'fixed_costs')
    ),
    record_id BIGINT NOT NULL,
    period VARCHAR(7) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


CREATE TABLE IF NOT EXISTS public.push_deliveries (
    event_id UUID NOT NULL REFERENCES public.push_events (id) ON DELETE CASCADE,
    endpoint_hash TEXT NOT NULL REFERENCES public.push_subscriptions (endpoint_hash) ON DELETE CASCADE,
    sent_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (event_id, endpoint_hash)
);


-- Lembretes de custos fixos são exclusivos de dispositivos ativados no APK Android.
