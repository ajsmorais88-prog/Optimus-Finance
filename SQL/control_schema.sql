DROP CONSTRAINT IF EXISTS push_events_route_check;


ALTER TABLE public.push_events
ADD CONSTRAINT push_events_route_check CHECK (
    route IN ('bank_account', 'card_bill', 'fixed_costs')
);


-- Sincronização automática: fila idempotente e versão de dados por usuário.
CREATE TABLE IF NOT EXISTS public.sync_jobs (
    job_key TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.app_users (id),
    kind TEXT NOT NULL,
    reference_id BIGINT NOT NULL,
    period VARCHAR(7),
    generation UUID NOT NULL,
    state TEXT NOT NULL,
    queued_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_success TIMESTAMPTZ,
    last_error TEXT,
    rerun BOOLEAN NOT NULL DEFAULT FALSE
);


CREATE TABLE IF NOT EXISTS public.sync_revisions (
    user_id BIGINT PRIMARY KEY REFERENCES public.app_users (id),
    revision BIGINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


ALTER TABLE public.pluggy_push_channels
ADD COLUMN IF NOT EXISTS sync_webhooks JSONB NOT NULL DEFAULT '{}';
